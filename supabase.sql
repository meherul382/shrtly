create table if not exists public.links (
  id bigint generated by default as identity primary key,
  code text not null unique,
  url text not null,
  image_url text,
  youtube_url text,
  clicks bigint not null default 0,
  created_at timestamptz not null default now()
);

alter table public.links add column if not exists youtube_url text;
alter table public.links add column if not exists link_mode text not null default 'advanced';
alter table public.links add column if not exists deleted_at timestamptz;
alter table public.links add column if not exists owner_token text;
alter table public.links add column if not exists user_id uuid;

create index if not exists links_code_idx on public.links(code);
create index if not exists links_user_deleted_idx on public.links(user_id, deleted_at, created_at);
create index if not exists links_owner_token_idx on public.links(owner_token, deleted_at, created_at);

create table if not exists public.analytics_visitors (
  id bigint generated by default as identity primary key,
  code text not null,
  visitor_id text not null,
  last_seen timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (code, visitor_id)
);

create index if not exists analytics_visitors_code_idx on public.analytics_visitors(code);
create index if not exists analytics_visitors_last_seen_idx on public.analytics_visitors(last_seen);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  plan text not null,
  link_limit integer not null,
  status text not null default 'pending',
  payment_method text,
  transaction_id text,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists subscriptions_user_status_idx on public.subscriptions(user_id, status, expires_at);

